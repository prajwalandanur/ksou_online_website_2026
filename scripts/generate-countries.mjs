/**
 * Regenerates src/constants/countries.js from Node's own ICU region data.
 *
 * Run manually (`node scripts/generate-countries.mjs`) — deliberately NOT
 * wired into `npm run build`, exactly like scripts/generate-favicons.mjs: the
 * output is committed so a build can never depend on the host's ICU version,
 * which would otherwise let the country list differ between a developer's
 * machine, CI and the prerender step.
 *
 * Hand-edit the ALIASES map below; everything else is derived.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

// Not places anyone applies from: exceptional reservations, groupings, and
// the uninhabited polar/island territories.
const SKIP = new Set([
  'AC', 'CP', 'DG', 'EA', 'EU', 'EZ', 'IC', 'QO', 'TA', 'UN', 'XA', 'XB', 'ZZ',
  'AQ', 'BV', 'HM', 'GS', 'UM', 'TF',
]);

/**
 * Withdrawn ISO 3166-1 codes that ICU still resolves, to the *same* display
 * name as their replacement — UK alongside GB, SU alongside RU, DD alongside
 * DE. Left in, the list showed "United Kingdom" twice with no way for a
 * visitor to tell the entries apart, and the wrong one could reach the
 * counsellor. Each of these is dropped in favour of its current code.
 */
const WITHDRAWN = new Set([
  'AN', 'BU', 'CS', 'CT', 'DD', 'DY', 'FQ', 'FX', 'HV', 'JT', 'MI', 'NH', 'NQ',
  'NT', 'PC', 'PU', 'PZ', 'RH', 'SU', 'TP', 'UK', 'VD', 'WK', 'YD', 'YU', 'ZR',
]);

// Search terms that are not substrings of the official name.
const ALIASES = {
  US: ['USA', 'US', 'America'],
  GB: ['UK', 'Britain', 'England', 'Scotland', 'Wales', 'Great Britain'],
  AE: ['UAE', 'Dubai', 'Abu Dhabi'],
  KR: ['South Korea'],
  KP: ['North Korea'],
  IN: ['Bharat'],
  NL: ['Holland'],
  MM: ['Burma'],
  CI: ['Ivory Coast'],
  CZ: ['Czech Republic'],
  TR: ['Turkey'],
  SZ: ['Swaziland'],
  CV: ['Cape Verde'],
  MK: ['Macedonia'],
  VA: ['Vatican'],
  RU: ['Russia'],
  LA: ['Laos'],
  SY: ['Syria'],
  IR: ['Iran'],
  TZ: ['Tanzania'],
  VE: ['Venezuela'],
  BO: ['Bolivia'],
  MD: ['Moldova'],
  BN: ['Brunei'],
  PS: ['Palestine'],
  CD: ['DRC', 'Congo Kinshasa'],
  CG: ['Congo Brazzaville'],
  HK: ['Hong Kong'],
  TW: ['Taiwan'],
};

const HEADER = [
  '/**',
  ' * ISO 3166-1 regions, for the enquiry form country combobox.',
  ' *',
  ' * Generated by scripts/generate-countries.mjs from Node own ICU data via',
  " * Intl.DisplayNames(['en'], { type: 'region' }) — every AA-ZZ code the data",
  ' * names, so the list is the platform version rather than a hand-typed subset',
  ' * that would quietly go stale. Committed rather than built at runtime:',
  ' * Intl.DisplayNames region data is not guaranteed on every browser, and the',
  ' * list has to be identical in the prerendered HTML and on the client.',
  ' *',
  ' * Dependencies and territories (Hong Kong, Puerto Rico, Reunion...) are kept',
  ' * — a student living in one should be able to say so. Dropped: exceptional',
  ' * reservations and groupings that are not places anyone applies from',
  ' * (EU, UN, AC, TA, DG, EA, IC, EZ, XA, XB, QO, ZZ) and the uninhabited',
  ' * polar/island territories (AQ, BV, HM, GS, UM, TF).',
  ' *',
  ' * `aliases` carry search terms that are not substrings of the official name',
  ' * — "UAE", "USA", "UK", "Holland". Without them, typing "UAE" finds nothing,',
  ' * because the stored name is "United Arab Emirates". They are search keys',
  ' * only and are never displayed.',
  ' *',
  ' * DO NOT EDIT BY HAND — edit the generator and re-run it.',
  ' */',
  '',
  '/** Pre-selected country: the large majority of KSOU Online applicants. */',
  "export const DEFAULT_COUNTRY_CODE = 'IN';",
  '',
  '',
].join('\n');

const display = new Intl.DisplayNames(['en'], { type: 'region', fallback: 'none' });
const countries = [];

for (let a = 65; a <= 90; a += 1) {
  for (let b = 65; b <= 90; b += 1) {
    const code = String.fromCharCode(a) + String.fromCharCode(b);
    if (SKIP.has(code) || WITHDRAWN.has(code)) continue;
    const name = display.of(code);
    if (name && name !== code) countries.push({ code, name });
  }
}

countries.sort((x, y) => x.name.localeCompare(y.name, 'en'));

// A duplicate name means ICU has grown another alias this list does not know
// about. Fail rather than ship two identical-looking options, one of which
// carries a code no system downstream will recognise.
const duplicates = countries
  .map((country) => country.name)
  .filter((name, index, all) => all.indexOf(name) !== index);

if (duplicates.length > 0) {
  throw new Error(
    `Duplicate country names — add the withdrawn code(s) to WITHDRAWN: ${[...new Set(duplicates)].join(', ')}`,
  );
}

// JSON.stringify rather than hand-rolled quoting: a handful of names carry an
// apostrophe (Cote d'Ivoire) and double quotes escape them without any
// backslash gymnastics.
const rows = countries.map(({ code, name }) => {
  const aliases = ALIASES[code];
  const fields = [`code: ${JSON.stringify(code)}`, `name: ${JSON.stringify(name)}`];
  if (aliases) fields.push(`aliases: [${aliases.map((a) => JSON.stringify(a)).join(', ')}]`);
  return `  { ${fields.join(', ')} },`;
});

writeFileSync(
  join(ROOT, 'src/constants/countries.js'),
  `${HEADER}export const COUNTRIES = [\n${rows.join('\n')}\n];\n`,
  'utf8',
);

console.log(`Wrote src/constants/countries.js — ${countries.length} regions.`);
